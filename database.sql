create policy "admins manage churches" on public.churches for all to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');
create policy "church users read own church" on public.churches for select to authenticated
using (public.current_role() = 'church' and id = public.current_church_id());

create policy "users read own profile" on public.profiles for select to authenticated
using (id = auth.uid() or public.current_role() = 'admin');
create policy "admins manage profiles" on public.profiles for all to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

create policy "authenticated read config" on public.app_config for select to authenticated
using (true);
create policy "admins manage config" on public.app_config for all to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');

create policy "admins manage payments" on public.payments for all to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');
create policy "church users read own payments" on public.payments for select to authenticated
using (public.current_role() = 'church' and church_id = public.current_church_id());
create policy "church users create own payments" on public.payments for insert to authenticated
with check (public.current_role() = 'church' and church_id = public.current_church_id() and submitted_by = auth.uid());

create policy "admins manage legal requests" on public.legal_requests for all to authenticated
using (public.current_role() = 'admin') with check (public.current_role() = 'admin');
create policy "church users read own requests" on public.legal_requests for select to authenticated
using (public.current_role() = 'church' and church_id = public.current_church_id());
create policy "church users create own requests" on public.legal_requests for insert to authenticated
with check (public.current_role() = 'church' and church_id = public.current_church_id() and submitted_by = auth.uid());

