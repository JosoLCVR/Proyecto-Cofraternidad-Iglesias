-- Cofraternidad: esquema inicial para Supabase/PostgreSQL
-- Ejecutar completo en Supabase > SQL Editor.

create extension if not exists pgcrypto;

create type public.user_role as enum ('admin', 'church');
create type public.church_status as enum ('Solvente', 'En mora', 'En proceso');
create type public.payment_status as enum ('Pendiente', 'Aprobado', 'Rechazado');
create type public.legal_status as enum ('Recibido', 'En análisis', 'En Notaría/Registro', 'Concluido', 'Rechazado');

create table public.churches (
  id bigint generated by default as identity primary key,
  name text not null,
  pastor text not null default '',
  rif text unique,
  phone text default '',
  email text default '',
  city text default 'Venezuela',
  address text default '',
  members integer not null default 0 check (members >= 0),
  status public.church_status not null default 'Solvente',
  initials text not null default 'IG',
  color text not null default 'bg-emerald-100 text-emerald-800 border-emerald-200',
  foundation_year integer check (foundation_year between 1800 and 2200),
  last_payment_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  role public.user_role not null default 'church',
  church_id bigint references public.churches(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint church_users_need_church check (role = 'admin' or church_id is not null)
);

create table public.app_config (
  id boolean primary key default true check (id),
  bcv_rate numeric(12, 4) not null default 45.50 check (bcv_rate > 0),
  org_name text not null default 'Cofraternidad de Iglesias',
  legal_department text not null default 'Departamento Legal y Registro',
  contact_phone text default '',
  contact_email text default '',
  whatsapp_support text default '',
  updated_at timestamptz not null default now()
);

create table public.payments (
  id bigint generated by default as identity primary key,
  church_id bigint not null references public.churches(id) on delete restrict,
  submitted_by uuid references auth.users(id) on delete set null,
  usd_amount numeric(14, 2) not null default 0 check (usd_amount >= 0),
  bs_amount numeric(14, 2) not null default 0 check (bs_amount >= 0),
  reference text not null,
  method text not null default 'Pago Móvil',
  concept text not null default 'Aporte Mensual',
  receipt_path text,
  status public.payment_status not null default 'Pendiente',
  notes text not null default '',
  account_destination text not null default '',
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (church_id, reference)
);

create table public.legal_requests (
  id bigint generated by default as identity primary key,
  church_id bigint not null references public.churches(id) on delete restrict,
  submitted_by uuid references auth.users(id) on delete set null,
  title text not null,
  category text not null default 'General',
  description text not null default '',
  lawyer text not null default 'Pendiente de asignación',
  status public.legal_status not null default 'Recibido',
  priority text not null default 'Media' check (priority in ('Alta', 'Media', 'Normal')),
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index payments_church_id_idx on public.payments(church_id);
create index payments_status_idx on public.payments(status);
create index legal_requests_church_id_idx on public.legal_requests(church_id);
create index legal_requests_status_idx on public.legal_requests(status);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger churches_updated_at before update on public.churches
for each row execute function public.set_updated_at();
create trigger legal_requests_updated_at before update on public.legal_requests
for each row execute function public.set_updated_at();

create or replace function public.current_role()
returns public.user_role
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid();
$$;

create or replace function public.current_church_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select church_id from public.profiles where id = auth.uid();
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name, role, church_id)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', new.email, ''),
    coalesce((new.raw_user_meta_data ->> 'role')::public.user_role, 'church'),
    nullif(new.raw_user_meta_data ->> 'church_id', '')::bigint
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

